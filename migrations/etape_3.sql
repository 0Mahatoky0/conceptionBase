CREATE TABLE commandes (
    id_commande INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date DATE
);

CREATE TABLE commande_plats (
    id_commande_plat INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_commande INT NOT NULL,
    id_plat INT,
    CONSTRAINT fk_commande_plat_commande FOREIGN KEY (id_commande) REFERENCES commandes(id_commande)
);

